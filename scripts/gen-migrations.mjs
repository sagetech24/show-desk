import { readdir, readFile, writeFile } from "node:fs/promises";

const files = (await readdir("migrations")).filter((f) => f.endsWith(".sql")).sort();
const entries = [];
for (const f of files) entries.push([f, await readFile(`migrations/${f}`, "utf8")]);
const out = `// Generated by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit.\nexport const MIGRATIONS: [string, string][] = ${JSON.stringify(entries, null, 2)};\n`;
await writeFile("src/lib/migrations.generated.ts", out);
console.log(`gen-migrations: ${files.length} file(s)`);
